test("malformed worker completion refuses, and arbitrary callback exceptions are internal", async () => {
  for (const reply of [
    Buffer.from("{"),
    Buffer.from("{}"),
    Buffer.from('{"adjusted_hex":[],"display_hex":[],"extra":1}'),
    Buffer.alloc(EXECUTION.workerBytes + 1),
  ]) {
    const out = await evaluateInner(encode(record()), expected, options, {
      runner: async () => reply,
    });
    assert.equal(out.refusal_kind, "internal_error");
    assert.equal(Object.hasOwn(out, "conformance"), false);
  }
  for (const error of [
    new TypeError("unexpected"),
    new SyntaxError("unexpected"),
    new GraphInvariantError("broken graph"),
  ]) {
    const out = await evaluateInner(
      encode(record()),
      () => {
        throw error;
      },
      options,
      harness,
    );
    assert.equal(out.refusal_kind, "internal_error");
  }
});

test("wire mutations and even graph-consistent fabricated S pass fail against private evidence", async () => {
  const edits = [
    (o: any) => {
      o.conformance[0].outcome = "fail";
    },
    (o: any) => {
      [o.conformance[0], o.verification[0]] = [
        o.verification[0],
        o.conformance[0],
      ];
    },
    (o: any) => {
      o.verification[2].scope.result_id = "other";
    },
    (o: any) => {
      o.record_reference.stored_projection_digest = "sha256:" + "0".repeat(64);
    },
    (o: any) => {
      o.verification[2].reasons = ["candidate:holm:context_mismatch"];
    },
    (o: any) => {
      o.protocol = "candidate.4";
    },
  ];
  for (const beforeValidate of edits)
    assert.equal(
      (
        await evaluateInner(encode(record()), expected, options, {
          ...harness,
          beforeValidate,
        })
      ).refusal_kind,
      "internal_error",
    );
  const r = record();
  r.payload = {};
  const local = inspectLocalRecord(encode(r), expected, noop, "candidate.5");
  const goodLocal = inspectLocalRecord(
    encode(record()),
    expected,
    noop,
    "candidate.5",
  );
  const fake = makeReport({
    local: goodLocal,
    arithmetic: { execution: "completed", outcome: "pass", reasons: [] },
  });
  fake.record_reference = makeReport({ local }).record_reference;
  assert.throws(() => validateCompletion(fake, { local }), GraphInvariantError);
});

test("late shared-budget failure supersedes a complete inner report", async () => {
  let late = false;
  const out = await evaluateInner(encode(record()), expected, options, {
    ...harness,
    beforeValidate: () => {
      late = true;
    },
    budget: {
      checkpoint() {
        if (late)
          throw new InvocationError("resource_limit", "processing_heap");
      },
      remainingMs: () => 5000,
    },
  });
  assert.equal(out.refusal_kind, "resource_limit");
  assert.equal(Object.hasOwn(out, "verification"), false);
  let now = 0;
  const budget = createBudget(undefined, { now: () => now, heap: () => 0 });
  now = 5000;
  budget.checkpoint();
  now = 5001;
  assert.throws(() => budget.checkpoint(), InvocationError);
  let heap = EXECUTION.heapBytes;
  const memory = createBudget(undefined, { now: () => 0, heap: () => heap });
  memory.checkpoint();
  heap++;
  assert.throws(() => memory.checkpoint(), InvocationError);
});

test("bounded file adapter checks actual bytes and preserves S-failure no-read behavior", async () => {
  const dir = mkdtempSync(join(tmpdir(), "holm-inner-"));
  try {
    const rp = join(dir, "record"),
      ep = join(dir, "expected"),
      small = join(dir, "small");
    writeFileSync(rp, encode(record()));
    writeFileSync(ep, expected());
    assert.equal(
      (await evaluateInnerFiles(rp, ep, options, harness)).kind,
      "report",
    );
    const missing = await evaluateInnerFiles(
      rp,
      join(dir, "missing"),
      options,
      harness,
    );
    assert.equal(outcome(missing, "C").execution, "error");
    const r = record();
    r.payload = {};
    writeFileSync(rp, encode(r));
    writeFileSync(ep, Buffer.alloc(1572865));
    assert.equal(
      (await evaluateInnerFiles(rp, ep, options, harness)).kind,
      "report",
    );
    writeFileSync(rp, encode(record()));
    assert.equal(
      (await evaluateInnerFiles(rp, ep, options, harness)).refusal_kind,
      "resource_limit",
    );
    for (const size of [7, 8, 9]) {
      writeFileSync(small, Buffer.alloc(size));
      if (size <= 8) assert.equal(readBounded(small, 8, noop).length, size);
      else assert.throws(() => readBounded(small, 8, noop), InvocationError);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

