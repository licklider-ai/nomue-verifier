test("cancellation is an invocation refusal; copied arithmetic cannot rewrite private inspected data", async () => {
  const ac = new AbortController();
  ac.abort();
  const out = await evaluateInner(
    encode(record()),
    expected,
    { ...options, signal: ac.signal },
    harness,
  );
  assert.equal(out.refusal_kind, "execution_cancelled");
  const local = inspectLocalRecord(
    encode(record()),
    expected,
    noop,
    "candidate.5",
  );
  const first = preparedArithmetic(local)!;
  first.submitted[0].adjusted_hex = "0";
  assert.notEqual(preparedArithmetic(local)!.submitted[0].adjusted_hex, "0");
  assert.equal(preparedArithmetic(structuredClone(local)), undefined);
  assert.equal(
    compareArithmetic(fixedReply, preparedArithmetic(local)!, noop).execution,
    "completed",
  );
});

